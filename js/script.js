  /* ==========================================================
     9. MOTOR DE CARRUSEL GENÉRICO (reutilizado por Directiva y Comunidad)
     ========================================================== */
  function createCardCarousel({
    trackEl,
    wrapperEl,
    prevBtn,
    nextBtn,
    dotsContainer,
    currentEl,
    totalEl,
    autoplayMs = 5500,
    onCardClick = null,
  }) {
    if (!trackEl) return null;

    let cards = Array.from(trackEl.children);
    let currentIndex = 0;
    let autoplay;

    function visibleCards() {
      if (window.innerWidth <= 640) return 1;
      if (window.innerWidth <= 900) return 2;
      if (window.innerWidth <= 1150) return 3;
      return 4;
    }

    function maxIndex() {
      return Math.max(0, cards.length - visibleCards());
    }

    function createDots() {
      if (!dotsContainer) return;
      dotsContainer.innerHTML = "";
      for (let i = 0; i <= maxIndex(); i++) {
        const dot = document.createElement("button");
        dot.className = "carousel-dot";
        dot.type = "button";
        dot.setAttribute("aria-label", `Ir a posición ${i + 1}`);
        dot.addEventListener("click", () => {
          currentIndex = i;
          update();
          restartAutoplay();
        });
        dotsContainer.appendChild(dot);
      }
    }

    function updateDots() {
      if (!dotsContainer) return;
      Array.from(dotsContainer.children).forEach((dot, index) => {
        dot.classList.toggle("active", index === currentIndex);
      });
      if (currentEl)
        currentEl.textContent = String(currentIndex + 1).padStart(2, "0");
      if (totalEl)
        totalEl.textContent = String(maxIndex() + 1).padStart(2, "0");
    }

    function update() {
      if (!cards.length) return;
      const cardWidth = cards[0].getBoundingClientRect().width;
      const gap = 24;
      const offset = currentIndex * (cardWidth + gap);
      trackEl.style.transform = `translate3d(-${offset}px, 0, 0)`;
      updateDots();
    }

    function next() {
      currentIndex = currentIndex >= maxIndex() ? 0 : currentIndex + 1;
      update();
    }

    function prev() {
      currentIndex = currentIndex <= 0 ? maxIndex() : currentIndex - 1;
      update();
    }

    function startAutoplay() {
      clearInterval(autoplay);
      autoplay = setInterval(next, autoplayMs);
    }

    function stopAutoplay() {
      clearInterval(autoplay);
    }

    function restartAutoplay() {
      startAutoplay();
    }

    if (nextBtn)
      nextBtn.addEventListener("click", () => {
        next();
        restartAutoplay();
      });
    if (prevBtn)
      prevBtn.addEventListener("click", () => {
        prev();
        restartAutoplay();
      });

    if (wrapperEl) {
      wrapperEl.addEventListener("mouseenter", stopAutoplay);
      wrapperEl.addEventListener("mouseleave", startAutoplay);
    }

    if (onCardClick) {
      cards.forEach((card, index) => {
        const trigger = card.querySelector("[data-open-detail]") || card;
        trigger.addEventListener("click", (event) => {
          event.stopPropagation();
          onCardClick(index);
        });
      });
    }

    window.addEventListener("resize", () => {
      currentIndex = Math.min(currentIndex, maxIndex());
      createDots();
      update();
    });

    createDots();
    update();
    startAutoplay();

    return { next, prev, stopAutoplay, startAutoplay, refresh: update };
  }

